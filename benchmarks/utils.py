from synaptoroute.profile import get_profile, ProfileType

def load_datasets(data_dir: str = "benchmarks/datasets") -> Tuple[str, List[Dict], List[Dict]]:
    """Loads all JSON datasets and merges them into a single list of routes and queries."""
    all_routes = []
    all_queries = []
    version = "unknown"
    
    version_path = os.path.join(data_dir, "VERSION")
    if os.path.exists(version_path):
        with open(version_path, "r", encoding="utf-8") as f:
            version = f.read().strip()
            
    # Load standard datasets (from standard/ folder generated by validate_dataset)
    standard_dir = os.path.join(data_dir, "standard")
    if os.path.exists(standard_dir):
        for filename in os.listdir(standard_dir):
            if filename.endswith(".json"):
                filepath = os.path.join(standard_dir, filename)
                with open(filepath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    all_routes.extend(data.get("routes", []))
                    all_queries.extend(data.get("test_queries", []))
    else:
        # Fallback to root directory
        for filename in os.listdir(data_dir):
            if filename.endswith(".json"):
                filepath = os.path.join(data_dir, filename)
                with open(filepath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    all_routes.extend(data.get("routes", []))
                    all_queries.extend(data.get("test_queries", []))
                    
    # Load community datasets
    community_dir = os.path.join(data_dir, "community")
    if os.path.exists(community_dir):
        for filename in os.listdir(community_dir):
            if filename.endswith(".json"):
                filepath = os.path.join(community_dir, filename)
                with open(filepath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    all_routes.extend(data.get("routes", []))
                    all_queries.extend(data.get("test_queries", []))
                
    return version, all_routes, all_queries

def init_synaptoroute(routes_data: List[Dict], model_name: str = "BAAI/bge-small-en-v1.5", storage_path: str = "bench_synapto.sqlite") -> AdaptiveRouter:
    """Initializes a SynaptoRoute instance with the given routes."""
    if os.path.exists(storage_path):
        os.remove(storage_path)
        
    encoder = SynaptoEncoder(model_name=model_name, providers=["CUDAExecutionProvider", "CPUExecutionProvider"])
    storage = SQLiteStorage(storage_path)
    profile = get_profile(ProfileType.THROUGHPUT)
    router = AdaptiveRouter(encoder=encoder, storage=storage, profile=profile)
    
    for route_data in routes_data:
        route = SynaptoRoute(name=route_data["name"], utterances=route_data["utterances"])
        router.add_route(route)
        
    return router

def init_semantic_router(routes_data: List[Dict], model_name: str = "BAAI/bge-small-en-v1.5") -> RouteLayer:
    """Initializes a semantic-router instance with the given routes."""
    encoder = SemanticFastEmbedEncoder(name=model_name)
    layer = RouteLayer(encoder=encoder, routes=[])
    
    for route_data in routes_data:
        route = SemanticRoute(name=route_data["name"], utterances=route_data["utterances"])
        layer.add(route)
        
    return layer
